// Copies the picture packs out of the iOS app's art source (inkset-games/core,
// games/tiny-worlds-ios/art-src/prototype.html) into packs.js, so the web build and the app share one set of art.
// Usage: node sync-art.js path/to/core/games/tiny-worlds-ios/art-src/prototype.html
const fs = require("fs"), path = require("path");
const src = process.argv[2];
if (!src) { console.error("usage: node sync-art.js <prototype.html>"); process.exit(1); }
const h = fs.readFileSync(src, "utf8");
const start = h.indexOf("const PACKS = ["), end = h.indexOf("];\nlet PACK = 0;", start);
if (start < 0 || end < 0) throw new Error("PACKS block not found in " + src);
const body = h.slice(start, end + 2);
const PACKS = new Function(body + "\nreturn PACKS;")();
const out = "// Generated by sync-art.js from inkset-games/core games/tiny-worlds-ios/art-src/prototype.html. Don't edit by hand.\n" + body + "\n";
fs.writeFileSync(path.join(__dirname, "packs.js"), out);
console.log("wrote packs.js:", PACKS.map((p) => `${p.name} (${p.worlds.map((w) => (w.svg.match(/data-c=/g) || []).length).join("/")} areas)`).join(", "));
